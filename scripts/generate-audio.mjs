// Generates the static mindfulness clips and the metal riff with ElevenLabs.
// Runs once at build time; the app itself never talks to ElevenLabs and ships no key.
//
//   ELEVENLABS_API_KEY=... npm run generate:audio
//   npm run generate:audio -- --force   # regenerate files that already exist
//
// The SDK reads ELEVENLABS_API_KEY from the environment.
import { ElevenLabsClient } from "@elevenlabs/elevenlabs-js";
import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const audioDir = join(root, "audio");
const force = process.argv.includes("--force");

const config = JSON.parse(await readFile(join(audioDir, "mindfulness.json"), "utf8"));

async function save(stream, file) {
  const chunks = [];
  for await (const chunk of stream) chunks.push(chunk);
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, Buffer.concat(chunks));
}

function clipPath(setIndex, lineIndex) {
  return join(audioDir, `set-${setIndex + 1}`, `${String(lineIndex + 1).padStart(2, "0")}.mp3`);
}

// audio/clips.js is loaded by index.html with a <script> tag, so it works when
// the app is opened straight from disk (file://), where fetch() of JSON fails.
const manifest = {
  riff: `audio/${config.riff.file}`,
  sets: config.sets.map((set, s) => ({
    title: set.title,
    clips: set.lines.map((text, l) => ({
      text,
      src: `audio/set-${s + 1}/${String(l + 1).padStart(2, "0")}.mp3`,
    })),
  })),
};
await writeFile(
  join(audioDir, "clips.js"),
  `// Generated by scripts/generate-audio.mjs from audio/mindfulness.json. Do not edit.\nwindow.PUSTEROM_AUDIO = ${JSON.stringify(manifest, null, 2)};\n`,
);
console.log("✓ audio/clips.js");
if (process.argv.includes("--manifest-only")) process.exit(0);

const client = new ElevenLabsClient();

let made = 0;
let skipped = 0;

for (const [s, set] of config.sets.entries()) {
  for (const [l, text] of set.lines.entries()) {
    const file = clipPath(s, l);
    if (!force && existsSync(file)) { skipped++; continue; }
    const audio = await client.textToSpeech.convert(config.voiceId, {
      text,
      modelId: config.modelId,
      outputFormat: "mp3_44100_128",
      voiceSettings: { stability: 0.7, similarityBoost: 0.8, style: 0.1, speed: 0.9 },
    });
    await save(audio, file);
    made++;
    console.log(`✓ ${set.title} ${l + 1}/10`);
  }
}

const riffFile = join(audioDir, config.riff.file);
if (force || !existsSync(riffFile)) {
  const riff = await client.music.compose({
    prompt: config.riff.prompt,
    musicLengthMs: config.riff.lengthMs,
    forceInstrumental: true,
  });
  await save(riff, riffFile);
  made++;
  console.log("✓ metal riff");
} else {
  skipped++;
}

console.log(`Done: ${made} generated, ${skipped} already existed.`);
